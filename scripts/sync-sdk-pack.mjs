import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packRoot = join(root, "packages", "sdk-packs", "sdk-57");
const templateRoot = join(packRoot, "template");
const generatedPath = join(packRoot, "src", "template.generated.ts");
const manifestPath = join(packRoot, "pack.json");
const checkOnly = process.argv.includes("--check");

function collectFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const absolute = join(directory, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`SDK packs cannot contain symlinks: ${absolute}`);
    return entry.isDirectory() ? collectFiles(absolute) : [absolute];
  });
}

const files = Object.fromEntries(
  collectFiles(templateRoot)
    .map((path) => [relative(templateRoot, path).replaceAll("\\", "/"), readFileSync(path, "utf8")])
    .sort(([left], [right]) => left.localeCompare(right)),
);
const hash = createHash("sha256");
for (const [path, content] of Object.entries(files)) {
  hash.update(path);
  hash.update("\0");
  hash.update(content);
  hash.update("\0");
}
const checksum = hash.digest("hex");
const generated = `// Generated by scripts/sync-sdk-pack.mjs. Do not edit.\nexport const sdk57FilesSha256 = ${JSON.stringify(checksum)};\nexport const sdk57Files: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(files, null, 2)});\n`;
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
manifest.filesSha256 = checksum;
const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;

if (checkOnly) {
  if (!existsSync(generatedPath) || readFileSync(generatedPath, "utf8") !== generated) {
    throw new Error("SDK 57 generated template is stale. Run pnpm sdk:sync.");
  }
  if (readFileSync(manifestPath, "utf8") !== manifestText) {
    throw new Error("SDK 57 manifest checksum is stale. Run pnpm sdk:sync.");
  }
  console.log(`SDK 57 checksum verified: ${checksum}`);
} else {
  writeFileSync(generatedPath, generated, "utf8");
  writeFileSync(manifestPath, manifestText, "utf8");
  console.log(`SDK 57 pack synchronized: ${checksum}`);
}
